-- 종가배팅 후보의 실측 성적표.
--
-- 후보 목록을 숫자 없이 내놓으면 추천으로 읽힙니다. 미국 급등 후보가 확률을 타입의
-- 일부로 들고 다니는 것과 같은 이유입니다 -- 종목만 늘어놓은 표는 "이거 사라"로
-- 읽히고, 우리는 그 말을 할 자격이 없습니다.
--
-- 여기 담기는 것은 각 등급이 과거에 실제로 어땠는가입니다. 갭의 절대값이 아니라
-- **그날 밤 시장 평균 갭 대비 초과분**입니다. 밤이 갭의 대부분을 정하기 때문입니다:
-- 2026-08의 세 밤에서 갭상승 확률이 43% / 71% / 30%였고, 그 폭 안에서는 어떤
-- 조건이든 좋아 보이게 만들 수 있습니다. 미국과 이란이 전쟁을 하면 모든 종목이
-- 같이 떨어지고 초과분은 그대로 남습니다.
--
-- 조건은 scripts/measure-close-bet.mjs가 50만 종목-밤에서 골라낸 것입니다. 각 항목이
-- 값을 더하는지 하나씩 빼서 확인했고, 그 결과가 조건 목록입니다.
--
--   활성화 양봉   +0.439%p 단독. 이어가는 양봉은 +0.021%p로 값이 없습니다
--   윗꼬리 30%↓   빼면 2.215 → 1.613%p
--   당일 10%↑     빼면 2.215 → 0.502%p. 가장 큰 기여
--   거래량 2배↑    더하면 2.006 → 2.215%p
--
-- 정배열은 뺐습니다. 넣으나 빼나 초과가 같고(2.058 vs 2.006) 후보만 29% 줄었습니다.
-- 단독으로도 +0.009%p로 50만 표본에서 사실상 0입니다 -- 종가배팅 글에서 가장 많이
-- 반복되는 조언인데 하룻밤에 대해서는 아무 값이 없습니다.
--
-- 등급은 당일 상승률로 나눕니다. 위로 갈수록 후보가 줄고 초과가 커집니다.

CREATE TABLE IF NOT EXISTS kr_close_bet_calibration (
  tier text PRIMARY KEY,
  min_day_move numeric NOT NULL,
  samples integer NOT NULL,
  nights integer NOT NULL,
  -- 밤 평균을 이긴 비율. 승률이 아니라 "밤만큼은 했는가"입니다.
  beat_rate numeric NOT NULL,
  -- 초과분 평균. 화면에 나가는 숫자는 이쪽입니다 -- 갭상승 빈도는 조건을 바꿔도
  -- 48~65%로 크게 안 움직이고, 움직이는 것은 초과폭입니다.
  excess_mean numeric NOT NULL,
  -- 갭상승 빈도. 초과분과 같이 보여야 오해가 없습니다.
  gap_up_rate numeric NOT NULL,
  calibrated_from date NOT NULL,
  calibrated_to date NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);
