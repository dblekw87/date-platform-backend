/**
 * 장 마감 뒤에 나온 것을 무엇으로 볼 것인가.
 *
 * 재는 쪽(measure-overnight-news.mjs)과 고르는 쪽(weekend-picks.mjs)이 같은
 * 분류를 써야 합니다. 여기가 갈리면 잰 것과 고른 것이 다른 조건이 되어, 측정이
 * 선정을 뒷받침하지 못합니다. [[weekend-news-backfill]]에서 백필과 평소 수집이
 * 같은 검색어를 쓰는 이유와 같습니다.
 */

/*
 * 복기 기사.
 *
 * 주말 헤드라인의 절반쯤이 이것입니다 -- 금요일에 오른 것을 다시 쓴 기사, 상한가
 * 목록, 수급 정리, 방송 추천. 사실은 이미 금요일 종가에 들어 있고 기사는 그
 * 사실을 옮긴 것뿐입니다. 언급수만 세면 이 기사들이 이깁니다(2026-09-05 주말
 * 실측: 언급 상위 30종목 중 절반이 금요일 급등주 복기였습니다).
 */
const recapPattern = /급등|급락|상한가|하한가|폭등|폭락|껑충|훈풍|강세|약세|마감|특징주|이격도|과열|수급\s*(분석|집중|엇갈|포착)|거래일|주차\s*(주가|코스)|주간\s*(코스닥|코스피|외국인|기관)|짚어보기|고래\s*종목|민원처리반|내일장|추천\s*종목|초고수|차익\s*실현|저가\s*매수|손절|익절|인기검색|검색\s*TOP|TOP\s*\d+\]|주가\s*[\d,]+원|[\d.]+%\s*(상승|하락|급등|급락|↑|↓)/;

/*
 * 새 재료.
 *
 * 장이 닫힌 뒤에 처음 나온 사실만 여기 해당합니다. 낱말은 공시 제목과 겹치게
 * 골랐습니다 -- 기사가 공시를 받아쓰는 것이 흔하고, 둘이 겹치면 같은 사건을
 * 두 경로로 확인한 셈이 되기 때문입니다.
 */
const materialPattern = /수주|공급계약|계약\s*체결|납품|낙찰|선정|출자|지분\s*(취득|인수)|타법인|인수|합병|주식\s*교환|자회사\s*편입|MOU|업무\s*협약|얼라이언스|출범|공동\s*개발|기공식|착공|준공|증설|양산|가동|신제품|출시|특허|승인|허가|임상|수출|진출|투자\s*유치|무상증자|자사주\s*(매입|소각|취득)|액면|병합|분할/;

/*
 * 아직 사실이 아닌 것.
 *
 * "수주 임박", "SMR 후속 수주 기대"는 낱말만 보면 재료와 구별되지 않지만 일어난
 * 일이 아닙니다. 아직 거래되지 않은 **사실**을 찾는 자리이므로 전망은 빠져야
 * 합니다. 2026-09-06 주말 후보에서 두산에너빌리티·한화오션·한화에어로스페이스가
 * 전부 이 종류였습니다.
 */
const speculativePattern = /기대|전망|관측|가능성|임박|촉각|주목|만지작|검토\s*중|예상|할까|될까|엿보|노린다|나설\s*듯/;

/*
 * 희석.
 *
 * 유상증자는 배정 방식이 부호를 뒤집습니다 -- 제3자배정은 돈을 넣는 쪽이 정해져
 * 있어 재료로 읽히고, 주주배정·일반공모는 기존 주주가 내는 돈입니다. 전환사채도
 * 같은 자리입니다. 이것을 material에 넣어 두는 바람에 2026-09-06 후보에 큐리언트
 * 1016억 주주배정 유상증자가 6위로 올라왔습니다.
 */
const dilutionPattern = /주주배정|일반공모|유상증자|전환사채|신주인수권|CB\s*발행|BW\s*발행|무상감자|감자\s*결정|출자전환/;

export function classifyHeadline(headline) {
  const text = String(headline ?? "");

  if (!text) return null;
  if (recapPattern.test(text)) return "recap";
  if (dilutionPattern.test(text)) return /제3자배정/.test(text) ? "material" : "dilution";
  if (speculativePattern.test(text)) return null;
  if (materialPattern.test(text)) return "material";

  return null;
}

/*
 * 공시.
 *
 * report_name이 DART가 붙인 이름이라 기사 제목보다 훨씬 정확합니다. 배정 방식은
 * 이름에 안 들어가는 경우가 있어 title도 같이 봅니다 -- 제3자배정은 돈을 넣는
 * 쪽이 정해져 있어 호재로 읽히고, 주주배정·일반공모는 기존 주주가 내는 돈이라
 * 반대로 읽힙니다.
 *
 * [기재정정]은 뺍니다. 이미 나온 공시의 오타를 고친 것이 대부분이라 새 사실이
 * 아닌데, 접수 시각은 오늘로 찍혀 창 안에 들어옵니다.
 */
export function classifyDisclosure(reportName, title) {
  const name = String(reportName ?? "");
  const text = `${name} ${String(title ?? "")}`;

  if (name.startsWith("[기재정정]")) return null;

  /*
   * 되돌리는 공시는 호재 낱말을 그대로 들고 옵니다.
   *
   * "자기주식취득신탁계약해지결정"은 자기주식취득으로 시작하지만 뜻은 반대입니다 --
   * 사던 것을 그만두는 것입니다. 2026-09-07 SK디스커버리가 이것으로 다음 장 후보에
   * 올라갔습니다. 해지·취소·철회·중단이 붙으면 아래 호재 판정으로 내려보내지 않습니다.
   */
  if (/해지|취소|철회|중단|미이행/.test(text)) return null;

  if (/불성실공시법인지정|관리종목|상장폐지|거래정지|횡령|배임|감사의견/.test(text)) return "bad";

  if (/전환사채권발행결정|신주인수권부사채|교환사채/.test(text)) return "dilution";

  if (/유상증자/.test(text)) {
    return /제3자배정/.test(text) ? "good" : "dilution";
  }

  if (/단일판매ㆍ공급계약체결|단일판매.공급계약|공급계약/.test(text)) return "good";
  if (/타법인주식및출자증권취득결정|회사합병결정|주식교환|영업양수/.test(text)) return "good";
  if (/자기주식취득|자기주식\s*신탁/.test(text)) return "good";

  return null;
}
